def detect_system_language():
    # Определяем системный язык Android или ОС ПК; если язык не входит в 6 поддерживаемых — возвращаем "en"
    try:
        from kivy.utils import platform
    except Exception:
        platform = "unknown"

    if platform == "android":
        try:
            from jnius import autoclass
            Locale = autoclass("java.util.Locale")
            sys_lang = str(Locale.getDefault().getLanguage() or "").lower()[:2]
            if sys_lang in SUPPORTED_CODES:
                return sys_lang
        except Exception:
            pass

    for env_key in ("LC_ALL", "LC_MESSAGES", "LANG"):
        val = os.environ.get(env_key, "")
        if val:
            code = val.split(".")[0].split("_")[0].lower()[:2]
            if code in SUPPORTED_CODES:
                return code

    try:
        loc = locale.getlocale()[0]
        if loc:
            code = str(loc).split("_")[0].lower()[:2]
            if code in SUPPORTED_CODES:
                return code
    except Exception:
        pass

    return "en"


def tr(key, lang="en", **kwargs):
    lang_dict = TRANSLATIONS.get(lang) or TRANSLATIONS["en"]
    template = lang_dict.get(key) or TRANSLATIONS["en"].get(key, key)
    if kwargs:
        try:
            return template.format(**kwargs)
        except Exception:
            return template
    return template
